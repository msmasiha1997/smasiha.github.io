"""Regenerate the sampling article's static SVG artwork (Python stdlib only).

Particle positions and distance checkpoints come from ula-examples.json,
generated by check_ula.py from the browser's actual ULA implementation. The
normal-displacement illustration evaluates that same analytic toy potential
directly. The normal-slices block and blog thumbnail are replaced.
The separate build_sampling_experiments.py maintains the four live experiments.
"""

import argparse
import json
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'docs/assets/data/ula-examples.json'
ARTICLE = ROOT / 'docs/writing/sampling-hidden-solutions/index.html'
THUMBNAIL = ROOT / 'docs/assets/images/sampling-thumbnail.svg'


def coordinate_string(points):
    return ' '.join(f'{x:.2f},{y:.2f}' for x, y in points)


def circle_markup(particles, mapping, radius):
    return ''.join(f'<circle cx="{x:.2f}" cy="{y:.2f}" r="{radius}"/>'
                   for x, y in (mapping(p['x'], p['y']) for p in particles))


def geometry(parameters):
    a = parameters['baseA'] * parameters['radius']
    b = parameters['baseB'] * parameters['radius']
    cosine, sine = math.cos(parameters['angle']), math.sin(parameters['angle'])
    cx, cy = parameters['center']['x'], parameters['center']['y']
    return [(cx + cosine * a * math.cos(t) - sine * b * math.sin(t),
             cy + sine * a * math.cos(t) + cosine * b * math.sin(t))
            for t in (2 * math.pi * i / 180 for i in range(181))]


def normal_slices(parameters):
    """A computed endpoint remains readable without JavaScript and in print."""
    radius = parameters['radius']
    a, b = parameters['baseA'] * radius, parameters['baseB'] * radius
    cosine, sine = math.cos(parameters['angle']), math.sin(parameters['angle'])
    cx, cy = parameters['center']['x'], parameters['center']['y']
    delta = .4

    def pixel(u, v):
        return (220 + 120 * (cx + cosine * u - sine * v),
                180 - 120 * (cy + sine * u + cosine * v))

    rows, probes, losses = [], [], []
    for key, label, axis, start, end, dx, dy in [
        ('a', 'A · right tip', parameters['baseA'], (a, 0), (a + delta, 0), -8, 32),
        ('b', 'B · top tip', parameters['baseB'], (0, b), (0, b + delta), -28, 8),
    ]:
        q = (radius + delta / axis) ** 2
        loss = (q - radius * radius) ** 2 / (1 + q)
        losses.append(loss)
        x0, y0 = pixel(*start)
        x1, y1 = pixel(*end)
        probes.append(f'''<g class="normal-probe normal-probe-{key}">
      <line data-normal-line="{key}" x1="{x0:.3f}" y1="{y0:.3f}" x2="{x1:.3f}" y2="{y1:.3f}"/>
      <circle class="normal-origin" cx="{x0:.3f}" cy="{y0:.3f}" r="6"/>
      <circle data-normal-point="{key}" cx="{x1:.3f}" cy="{y1:.3f}" r="7"/>
      <text x="{x0+dx:.3f}" y="{y0+dy:.3f}">{key.upper()}</text>
    </g>''')
        rows.append(f'''<div class="normal-loss-row normal-probe-{key}">
      <span class="normal-loss-label">{label}</span>
      <span class="normal-bar-track" aria-hidden="true"><span data-normal-bar="{key}" style="width: {loss / .5 * 100:.6f}%"></span></span>
      <span class="normal-loss-value" data-normal-loss="{key}">{loss:.3f}</span>
    </div>''')
    curve = coordinate_string((220 + 120*x, 180 - 120*y) for x, y in geometry(parameters))
    return f'''<figure class="story-figure normal-rise" id="normal-rise" aria-labelledby="normal-rise-title">
  <h3 id="normal-rise-title">Same distance away. Different rise in loss.</h3>
  <p class="normal-intro">Start at two minimizers, A and B. Move both points the same distance perpendicular to the curve.</p>
  <p class="normal-key">Curve = solution set <i>S</i> · every point on it has loss 0.</p>
  <svg data-normal-plot class="normal-plot" viewBox="0 0 480 330" role="img" aria-labelledby="normal-plot-title normal-plot-desc">
    <title id="normal-plot-title">Comparing the loss near two minimizers</title>
    <desc id="normal-plot-desc" data-normal-desc>Both points move 0.40 units outward, perpendicular to the elliptical solution curve. Loss at A is {losses[0]:.3f}; loss at B is {losses[1]:.3f}. Equal displacements cause different increases in loss.</desc>
    <polyline class="normal-curve" points="{curve}"/>
    <text class="normal-set-label" x="220" y="190" text-anchor="middle">S</text>
    {''.join(probes)}
  </svg>
  <div class="normal-controls" data-normal-controls hidden>
    <button type="button" class="sampler-reset" data-normal-play aria-controls="normal-rise">Play</button>
    <div class="normal-range">
      <label for="normal-displacement">Distance moved from <i>S</i></label>
      <input id="normal-displacement" data-normal-slider type="range" min="0" max="0.4" step="0.01" value="0.4">
    </div>
  </div>
  <p class="normal-distance">Both points: <span data-normal-distance>0.40</span> units from <i>S</i>.</p>
  <div class="normal-losses" role="group" aria-labelledby="normal-loss-heading">
    <p id="normal-loss-heading">Increase in loss <span>· same scale, 0–0.50</span></p>
    {''.join(rows)}
  </div>
  <p class="normal-status" data-normal-status role="status" aria-live="polite">The same step raises the loss more at B. This steeper rise perpendicular to the solution set is what “greater normal stiffness” means.</p>
  <figcaption>“Normal stiffness” means how sharply loss rises perpendicular to the set. A gentler rise leaves more room for low-loss points nearby, giving more limiting probability per unit of arc length. Values come from the actual toy loss.</figcaption>
</figure>'''


def thumbnail(data, curve):
    mapping = lambda x, y: (160 + 80 * x, 94 - 80 * y)
    run = next(r for r in data['final'] if r['temperature'] == .06)
    target = coordinate_string(mapping(x, y) for x, y in curve)
    # A deliberate pale-blue background and explicit ink keep an external
    # <img> legible in either site theme; currentColor cannot inherit across it.
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 320 188" role="img" aria-labelledby="title desc" style="color:#2458a6">
<title id="title">Sampling near a hidden solution set</title>
<desc id="desc">Sixty-four numerically simulated ULA particles around an elliptical set of minimizers after 6000 steps, at temperature 0.06.</desc>
<rect width="320" height="188" rx="8" fill="#edf3fa"/>
<polyline points="{target}" fill="none" stroke="currentColor" stroke-width="1.6" stroke-opacity=".55"/>
<g fill="currentColor" fill-opacity=".8">{circle_markup(run['particles'], mapping, 2.8)}</g>
</svg>\n'''


def replace_block(source, name, content):
    pattern = re.compile(r'(<!-- ' + re.escape(name) + r':start -->).*?(<!-- ' + re.escape(name) + r':end -->)', re.S)
    if len(pattern.findall(source)) != 1:
        raise ValueError(f'Expected exactly one {name} block; refusing to alter the article.')
    return pattern.sub(lambda match: match[1] + '\n' + content + '\n' + match[2], source)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check generated files without writing them.')
    args = parser.parse_args()
    data = json.loads(DATA.read_text())
    curve = geometry(data['parameters'])
    blocks = {
        'normal-slices': normal_slices(data['parameters']),
    }
    original = ARTICLE.read_text()
    updated = original
    for name, markup in blocks.items():
        updated = replace_block(updated, name, markup)
    svg = thumbnail(data, curve)
    if args.check:
        assert original == updated, 'Generated article blocks are stale.'
        assert THUMBNAIL.exists() and THUMBNAIL.read_text() == svg, 'Sampling thumbnail is stale.'
        print('PASS: normal-displacement illustration and sampling thumbnail match the numerical source.')
    else:
        ARTICLE.write_text(updated)
        THUMBNAIL.write_text(svg)
        print('Regenerated normal-displacement illustration and docs/assets/images/sampling-thumbnail.svg')


if __name__ == '__main__':
    main()
